//! Human outputs: terminal summary and the `MAP.md` navigation map for agents.

use std::fmt::Write as _;

use crate::audit::{Report, Severity};
use crate::manifest::AppDir;

/// Terminal summary with every finding.
#[must_use]
pub fn summary(report: &Report) -> String {
    let mut s = String::new();
    let _ = writeln!(
        s,
        "nopray audit · {} {} · {} · tier {:?} · exposure {:?}\nimage {} bytes · sha256 {}",
        report.app,
        report.version,
        report.isa,
        report.tier,
        report.exposure,
        report.size,
        report.sha256
    );
    if let Some(r) = &report.reference {
        let _ = writeln!(s, "reference: {r}");
    }
    let _ = writeln!(
        s,
        "syscalls used: {}",
        if report.syscall_set.is_empty() {
            "-".into()
        } else {
            report
                .syscall_set
                .iter()
                .cloned()
                .collect::<Vec<_>>()
                .join(", ")
        }
    );
    if let Some(o) = &report.origin {
        let _ = writeln!(s, "{}", origin_line(o));
    }
    for f in &report.findings {
        let loc = match (&f.slot, f.addr) {
            (Some(sl), Some(a)) => format!("{sl}@{a:#x}"),
            (Some(sl), None) => sl.clone(),
            (None, Some(a)) => format!("{a:#x}"),
            (None, None) => "-".into(),
        };
        let _ = writeln!(s, "{} {} {:<24} {}", f.severity, f.code, loc, f.message);
    }
    let _ = writeln!(
        s,
        "result: {} error(s), {} warning(s), {} info",
        report.count(Severity::Error),
        report.count(Severity::Warning),
        report.count(Severity::Info)
    );
    s
}

fn origin_line(o: &crate::audit::OriginTotals) -> String {
    format!(
        "origin (used bytes): authored {} · reauthored {} · imported {} · undeclared {} · hand-written {}.{}%",
        o.authored,
        o.reauthored,
        o.imported,
        o.undeclared,
        o.hand_written_permille() / 10,
        o.hand_written_permille() % 10
    )
}

fn list(set: &std::collections::BTreeSet<String>) -> String {
    if set.is_empty() {
        "-".into()
    } else {
        set.iter()
            .map(|x| format!("`{x}`"))
            .collect::<Vec<_>>()
            .join(", ")
    }
}

/// Markdown map: segments, slots, call graph, syscalls, state ownership and open findings.
#[must_use]
pub fn map(app: &AppDir, report: &Report) -> String {
    let m = &app.manifest;
    let mut s = String::new();
    let _ = writeln!(s, "# MAP · {} {}\n", m.app.name, m.app.version);
    let _ = writeln!(
        s,
        "> Generated by `nopray audit` from `nopray.toml` and the slot bytes. Do not edit by hand.\n"
    );
    let _ = writeln!(
        s,
        "| Field | Value |\n|---|---|\n| Standard / tier | {} / {:?} |\n| Exposure | {:?} |\n| Target | {} · {:?} · {:?} |\n| Entry | `{}` |\n| Image | {} bytes |\n| SHA-256 | `{}` |\n| Audit | {} errors · {} warnings |\n",
        m.app.standard,
        m.app.tier,
        m.app.exposure,
        m.target.isa,
        m.target.os,
        m.target.format,
        m.target.entry,
        report.size,
        report.sha256,
        report.count(Severity::Error),
        report.count(Severity::Warning)
    );
    if let Some(o) = &report.origin {
        let _ = writeln!(s, "{}\n", origin_line(o));
    }
    if let Some(d) = &m.app.description {
        let _ = writeln!(s, "{d}\n");
    }
    if !m.segments.is_empty() {
        let _ = writeln!(
            s,
            "## Segments\n\n| Name | vaddr | file off | filesz | memsz | perms |\n|---|---|---|---|---|---|"
        );
        for g in &m.segments {
            let _ = writeln!(
                s,
                "| {} | `{:#x}` | `{:#x}` | `{:#x}` | `{:#x}` | `{}` |",
                g.name, g.vaddr, g.offset, g.file_size, g.mem_size, g.perms
            );
        }
        s.push('\n');
    }
    let _ = writeln!(
        s,
        "## Slots\n\n| Slot | Kind | vaddr | used / size | sha256 | Purpose |\n|---|---|---|---|---|---|"
    );
    for r in &report.slots {
        let _ = writeln!(
            s,
            "| `{}` | {} | `{}` | {} / {} | `{}` | {} |",
            r.name,
            r.kind,
            r.vaddr,
            r.used,
            r.size,
            &r.sha256[..12],
            r.purpose.replace('|', "/")
        );
    }
    let _ = writeln!(s, "\n## Code slots: calls, data and state\n");
    for r in report.slots.iter().filter(|r| r.kind == "code") {
        let slot = m
            .slots
            .iter()
            .find(|x| x.name == r.name)
            .expect("report mirrors manifest");
        let _ = writeln!(s, "### `{}` · `{}`\n", r.name, r.vaddr);
        let _ = writeln!(s, "- Purpose: {}", r.purpose);
        if let Some(c) = &slot.contract {
            let _ = writeln!(
                s,
                "- Contract: in {} · out {} · clobbers {}{}",
                if c.inputs.is_empty() {
                    "-".into()
                } else {
                    c.inputs.join("; ")
                },
                if c.outputs.is_empty() {
                    "-".into()
                } else {
                    c.outputs.join("; ")
                },
                if c.clobbers.is_empty() {
                    "-".into()
                } else {
                    c.clobbers.join(", ")
                },
                if c.noreturn { " · noreturn" } else { "" }
            );
        }
        let coverage = r
            .coverage
            .map_or_else(|| "-".to_owned(), |c| format!("{c:?}"));
        let _ = writeln!(
            s,
            "- Decoded: {} instructions · coverage {coverage}",
            r.instructions
        );
        if r.origin.is_some() || r.fields > 0 {
            let _ = writeln!(
                s,
                "- Origin: {} · symbolic fields: {}",
                r.origin.map_or_else(
                    || "undeclared".to_owned(),
                    |o| format!("{o:?}").to_lowercase()
                ),
                r.fields
            );
        }
        let _ = writeln!(
            s,
            "- Intents: {} declared · {} mismatched",
            r.intents, r.intent_mismatches
        );
        let _ = writeln!(
            s,
            "- Calls: {} · Jumps to: {}",
            list(&r.calls),
            list(&r.jumps_to)
        );
        let _ = writeln!(
            s,
            "- Called by: {} · Referenced by: {}",
            list(&r.called_by),
            list(&r.referenced_by)
        );
        let _ = writeln!(s, "- Data used: {}", list(&r.data_refs));
        let _ = writeln!(s, "- Syscalls: {}", list(&r.syscalls));
        if !r.state_reads.is_empty() || !r.state_writes.is_empty() {
            let _ = writeln!(
                s,
                "- State reads: {} · writes: {}",
                list(&r.state_reads),
                list(&r.state_writes)
            );
        }
        let _ = writeln!(s, "- Registers written: {}", list(&r.writes));
        if r.indirect_branches > 0 {
            let _ = writeln!(
                s,
                "- Indirect branches: {} ({})",
                r.indirect_branches,
                slot.indirect.as_deref().unwrap_or("UNJUSTIFIED")
            );
        }
        if !slot.labels.is_empty() {
            let labels: Vec<String> = slot
                .labels
                .iter()
                .map(|l| {
                    format!(
                        "`{}`@+{:#x}{}",
                        l.name,
                        l.offset,
                        if l.entry { " (entry)" } else { "" }
                    )
                })
                .collect();
            let _ = writeln!(s, "- Labels: {}", labels.join(", "));
        }
        s.push('\n');
    }
    if !report.syscall_sites.is_empty() {
        let _ = writeln!(
            s,
            "## Syscall sites\n\n| Slot | Address | Nr | Name |\n|---|---|---|---|"
        );
        for site in &report.syscall_sites {
            let _ = writeln!(
                s,
                "| `{}` | `{}` | {} | {} |",
                site.slot,
                site.addr,
                site.number.map_or("?".into(), |n| n.to_string()),
                site.name.as_deref().unwrap_or("UNRESOLVED")
            );
        }
        s.push('\n');
    }
    if !m.state.is_empty() {
        let _ = writeln!(
            s,
            "## State fields\n\n| Field | vaddr | size | Written by | Read by |\n|---|---|---|---|---|"
        );
        for f in &m.state {
            let writers: Vec<&str> = report
                .slots
                .iter()
                .filter(|r| r.state_writes.contains(&f.name))
                .map(|r| r.name.as_str())
                .collect();
            let readers: Vec<&str> = report
                .slots
                .iter()
                .filter(|r| r.state_reads.contains(&f.name))
                .map(|r| r.name.as_str())
                .collect();
            let _ = writeln!(
                s,
                "| `{}` | `{:#x}` | {} | {} | {} |",
                f.name,
                f.vaddr,
                f.size,
                writers.join(", "),
                readers.join(", ")
            );
        }
        s.push('\n');
    }
    let open: Vec<_> = report
        .findings
        .iter()
        .filter(|f| f.severity != Severity::Info)
        .collect();
    let _ = writeln!(s, "## Open findings\n");
    if open.is_empty() {
        let _ = writeln!(s, "None.");
    }
    for f in open {
        let _ = writeln!(
            s,
            "- **{}** `{}` {}{}",
            f.code,
            f.slot.as_deref().unwrap_or("-"),
            f.addr.map(|a| format!("`{a:#x}` ")).unwrap_or_default(),
            f.message
        );
    }
    s
}
